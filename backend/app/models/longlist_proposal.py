"""Longlist Proposal Model - Ranked supplier longlist proposal."""
from datetime import UTC, datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base

if TYPE_CHECKING:
    from app.models.proposal_supplier import ProposalSupplier


class LonglistProposal(Base):
    """Longlist proposal with ranked supplier recommendations.
    
    Records a ranked supplier proposal generated by AGN2.
    Each proposal has a version number and includes generation inputs for audit.
    """
    __tablename__ = "longlist_proposal"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    case_id: Mapped[int] = mapped_column(Integer, ForeignKey("need_case.id"), nullable=False, index=True)
    version_no: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    proposal_status: Mapped[str] = mapped_column(String(50), nullable=False, default="draft")
    generation_inputs: Mapped[str | None] = mapped_column(Text, nullable=True)
    generated_by_agent_run_id: Mapped[str | None] = mapped_column(String(100), nullable=True)
    requirement_tags: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), 
        nullable=False, 
        default=lambda: datetime.now(UTC)
    )
    
    # Relationship to suppliers in this proposal
    proposal_suppliers: Mapped[list["ProposalSupplier"]] = relationship(
        "ProposalSupplier", back_populates="proposal", cascade="all, delete-orphan"
    )
